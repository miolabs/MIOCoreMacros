//
//  JSBindings.swift
//  MIOExportCore
//
//  Finds the @Export functions in Swift sources and writes the JavaScript class that calls
//  them (on top of MIOCoreWasm's miowasm.js) plus its TypeScript declarations.
//

import SwiftSyntax
import SwiftParser

public enum ExportScanner {

    // The @Export functions of one source file, in order (also inside #if blocks).
    public static func scan ( source: String, file: String = "" ) throws -> [ExportedFunction] {
        let visitor = Visitor( viewMode: .sourceAccurate )
        visitor.walk( Parser.parse( source: source ) )
        if let error = visitor.errors.first { throw ExportError( ( file.isEmpty ? "" : file + ": " ) + error ) }
        return visitor.functions
    }

    final class Visitor: SyntaxVisitor {
        var functions: [ExportedFunction] = []
        var errors: [String] = []

        override func visit ( _ node: FunctionDeclSyntax ) -> SyntaxVisitorContinueKind {
            let attribute = node.attributes.lazy.compactMap { $0.as( AttributeSyntax.self ) }.first {
                let name = $0.attributeName.trimmedDescription
                return name == "Export" || name == "MIOCoreMacros.Export"
            }
            if let attribute = attribute {
                do { functions.append( try ExportedFunction( node, attribute: attribute ) ) }
                catch { errors.append( "\( node.name.text ): \( error )" ) }
            }
            return .skipChildren
        }
    }
}

public struct JSBindings {

    public var className: String
    // How the generated module imports MIOWasm.
    public var miowasmPath: String
    public var functions: [ExportedFunction]

    public init ( className: String, miowasmPath: String = "./miowasm.js", functions: [ExportedFunction] ) {
        self.className = className
        self.miowasmPath = miowasmPath
        self.functions = functions
    }

    static let reserved: Set<String> = [
        "arguments", "await", "break", "case", "catch", "class", "const", "continue", "debugger", "default",
        "delete", "do", "else", "enum", "eval", "export", "extends", "false", "finally", "for", "function",
        "if", "implements", "import", "in", "instanceof", "interface", "let", "new", "null", "package",
        "private", "protected", "public", "return", "static", "super", "switch", "this", "throw", "true",
        "try", "typeof", "var", "void", "while", "with", "yield",
    ]

    static func jsName ( _ name: String ) -> String { reserved.contains( name ) ? name + "_" : name }

    // MARK: JavaScript

    public var javaScript: String {
        var out = """
        // Generated by mio-wasm-bindings from the @Export functions. Do not edit.

        import { MIOWasm } from "\( miowasmPath )";

        export class \( className ) {

            // `source`: a fetch Response (or its promise), bytes or a WebAssembly.Module.
            static async instantiate( source, options = {} ) {
                return new this( await MIOWasm.instantiate( source, options ) );
            }

            constructor( wasm ) { this.wasm = wasm; }

            // Throws the error a failed call left (MCWasm.fail).
            _check() {
                const p = this.wasm.exports.mio_take_error();
                if ( p ) throw new Error( this.wasm.readString( p ) );
            }

        """
        for f in functions { out += "\n" + method( f ) }
        out += "}\n"
        return out
    }

    func method ( _ f: ExportedFunction ) -> String {
        var lines: [String] = []
        if !f.documentation.isEmpty {
            lines.append( "    /** " + f.documentation.joined( separator: "\n     *  " ) + " */" )
        }
        let names = f.parameters.map { JSBindings.jsName( $0.name ) }
        let declared = zip( f.parameters, names ).map { p, n in p.defaultLiteral.map { "\( n ) = \( $0 )" } ?? n }
        let passed = zip( f.parameters, names ).map { p, n -> String in
            switch p.type.kind {
            case .int, .int32: return "\( n ) | 0"
            case .double, .float: return "+\( n )"
            case .bool: return "!!\( n )"
            case .string, .data, .bytes: return n
            case .json: return p.type.optional ? "\( n ) == null ? null : JSON.stringify( \( n ) )" : "JSON.stringify( \( n ) )"
            }
        }
        lines.append( "    \( JSBindings.jsName( f.swiftName ) )\( declared.isEmpty ? "()" : "( " + declared.joined( separator: ", " ) + " )" ) {" )
        let call = "this.wasm.call( \( ( [ "\"\( f.symbol )\"" ] + passed ).joined( separator: ", " ) ) )"
        guard let result = f.result else {
            lines.append( "        \( call );" )
            if f.canFail { lines.append( "        this._check();" ) }
            lines.append( "    }" )
            return lines.joined( separator: "\n" ) + "\n"
        }
        lines.append( "        const r = \( call );" )
        if f.canFail { lines.append( "        this._check();" ) }
        let value: String
        switch result.kind {
        case .int, .int32, .double, .float: value = "r"
        case .bool: value = "r !== 0"
        case .string: value = result.optional ? "r === 0 ? null : this.wasm.readString( r )" : "this.wasm.readString( r )"
        case .data, .bytes: value = result.optional ? "r === 0 ? null : this.wasm.readBytes( r )" : "this.wasm.readBytes( r )"
        case .json: value = "this.wasm.readJSON( r )"
        }
        lines.append( "        return \( value );" )
        lines.append( "    }" )
        return lines.joined( separator: "\n" ) + "\n"
    }

    // MARK: TypeScript

    public var typeScript: String {
        var out = """
        // Generated by mio-wasm-bindings from the @Export functions. Do not edit.

        export declare class \( className ) {
            static instantiate<T extends typeof \( className )>( this: T, source: Response | PromiseLike<Response> | BufferSource | WebAssembly.Module, options?: { prefix?: string, log?: ( ...a: any[] ) => void, warn?: ( ...a: any[] ) => void } ): Promise<InstanceType<T>>;
            constructor( wasm: any );
            readonly wasm: any;

        """
        for f in functions {
            if !f.documentation.isEmpty {
                out += "    /** " + f.documentation.joined( separator: "\n     *  " ) + " */\n"
            }
            let params = f.parameters.map { p -> String in
                let t = tsType( p.type, argument: true )
                return JSBindings.jsName( p.name ) + ( p.defaultLiteral != nil ? "?" : "" ) + ": " + t
            }
            out += "    \( JSBindings.jsName( f.swiftName ) )\( params.isEmpty ? "()" : "( " + params.joined( separator: ", " ) + " )" ): \( f.result.map { tsType( $0, argument: false ) } ?? "void" );\n"
        }
        out += "}\n"
        return out
    }

    func tsType ( _ type: ExportType, argument: Bool ) -> String {
        let base: String
        switch type.kind {
        case .int, .int32, .double, .float: base = "number"
        case .bool: base = "boolean"
        case .string: base = "string"
        case .data, .bytes: base = argument ? "Uint8Array | string" : "Uint8Array"   // a string goes as UTF-8
        case .json: base = "any"
        }
        return type.optional && base != "any" ? base + " | null" : base
    }
}
